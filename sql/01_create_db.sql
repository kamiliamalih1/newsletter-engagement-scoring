CREATE DATABASE IF NOT EXISTS newsletter_scoring;
USE newsletter_scoring;

-- ============================================================
-- TABLE 1 : abonnes
-- ============================================================
CREATE TABLE abonnes (
    id_abonne    INT AUTO_INCREMENT PRIMARY KEY,
    email        VARCHAR(150) NOT NULL UNIQUE,
    prenom       VARCHAR(80)  NOT NULL,
    nom          VARCHAR(80)  NOT NULL,
    ville        VARCHAR(100),
    pays         VARCHAR(60)  DEFAULT 'France',
    date_inscription DATE NOT NULL,
    segment_age  VARCHAR(20),
    actif        TINYINT(1)   DEFAULT 1
);

-- ============================================================
-- TABLE 2 : campagnes
-- ============================================================
CREATE TABLE campagnes (
    id_campagne  INT AUTO_INCREMENT PRIMARY KEY,
    nom_campagne VARCHAR(150) NOT NULL,
    sujet        VARCHAR(255) NOT NULL,
    date_envoi   DATE NOT NULL,
    categorie    VARCHAR(60)  NOT NULL,  -- ex: promo, contenu, reactivation
    nb_envoyes   INT          NOT NULL DEFAULT 0
);

-- ============================================================
-- TABLE 3 : envois  (relation many-to-many abonnes <-> campagnes)
-- ============================================================
CREATE TABLE envois (
    id_envoi     INT AUTO_INCREMENT PRIMARY KEY,
    id_abonne    INT NOT NULL,
    id_campagne  INT NOT NULL,
    date_envoi   DATETIME NOT NULL,
    ouvert       TINYINT(1) DEFAULT 0,
    clique       TINYINT(1) DEFAULT 0,
    desabonne    TINYINT(1) DEFAULT 0,
    FOREIGN KEY (id_abonne)   REFERENCES abonnes(id_abonne),
    FOREIGN KEY (id_campagne) REFERENCES campagnes(id_campagne),
    UNIQUE KEY uq_abonne_campagne (id_abonne, id_campagne)
);

-- ============================================================
-- TABLE 4 : produits (pour enrichir le contexte e-commerce)
-- ============================================================
CREATE TABLE produits (
    id_produit   INT AUTO_INCREMENT PRIMARY KEY,
    nom_produit  VARCHAR(150) NOT NULL,
    categorie    VARCHAR(80)  NOT NULL,
    prix_ht      DECIMAL(8,2) NOT NULL,
    stock        INT DEFAULT 0
);

-- ============================================================
-- TABLE 5 : clics_produits  (many-to-many envois <-> produits)
-- ============================================================
CREATE TABLE clics_produits (
    id_clic      INT AUTO_INCREMENT PRIMARY KEY,
    id_envoi     INT NOT NULL,
    id_produit   INT NOT NULL,
    date_clic    DATETIME NOT NULL,
    FOREIGN KEY (id_envoi)   REFERENCES envois(id_envoi),
    FOREIGN KEY (id_produit) REFERENCES produits(id_produit)
);

